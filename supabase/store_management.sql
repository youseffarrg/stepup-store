-- STEPUP store management tables
-- Run this file in Supabase SQL Editor after the admin user has been added to public.stepup_admins.


create table if not exists public.stepup_products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  category text not null default 'رجالي',
  image_url text not null default '',
  purchase_price numeric(10,2) not null default 0 check (purchase_price >= 0),
  price numeric(10,2) not null default 0 check (price >= 0),
  sale_price numeric(10,2) check (sale_price is null or sale_price >= 0),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  sizes text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.stepup_orders (
  id bigint generated by default as identity primary key,
  order_number text not null unique default ('SU-' || to_char(now(), 'YYMMDD') || '-' || lpad(nextval('public.stepup_order_number_seq')::text, 5, '0')),
  product_id bigint references public.stepup_products(id) on delete set null,
  product_name text not null,
  quantity integer not null default 1 check (quantity > 0),
  unit_price numeric(10,2) not null default 0 check (unit_price >= 0),
  customer_name text not null,
  customer_phone text not null,
  customer_address text not null,
  size text not null default '',
  notes text not null default '',
  status text not null default 'new' check (status in ('new','confirmed','preparing','shipped','delivered','cancelled')),
  payment_method text not null default 'cash_on_delivery',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.stepup_products enable row level security;
alter table public.stepup_orders enable row level security;

drop policy if exists "Public can view active STEPUP products" on public.stepup_products;
create policy "Public can view active STEPUP products"
on public.stepup_products for select to anon, authenticated
using (is_active = true);

drop policy if exists "Managers manage STEPUP products" on public.stepup_products;
create policy "Managers manage STEPUP products"
on public.stepup_products for all to authenticated
using (exists (select 1 from public.stepup_admins a where a.user_id = auth.uid() and a.role in ('admin','manager')))
with check (exists (select 1 from public.stepup_admins a where a.user_id = auth.uid() and a.role in ('admin','manager')));

drop policy if exists "Public can create STEPUP orders" on public.stepup_orders;
create policy "Public can create STEPUP orders"
on public.stepup_orders for insert to anon, authenticated
with check (status = 'new' and quantity > 0 and length(trim(customer_name)) > 0 and length(trim(customer_phone)) > 0 and length(trim(customer_address)) > 0);

drop policy if exists "Managers manage STEPUP orders" on public.stepup_orders;
create policy "Managers manage STEPUP orders"
on public.stepup_orders for all to authenticated
using (exists (select 1 from public.stepup_admins a where a.user_id = auth.uid() and a.role in ('admin','manager')))
with check (exists (select 1 from public.stepup_admins a where a.user_id = auth.uid() and a.role in ('admin','manager')));

create sequence if not exists public.stepup_order_number_seq start 1;
