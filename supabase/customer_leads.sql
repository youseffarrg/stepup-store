-- STEPUP customer leads: run once in Supabase SQL Editor.
create table if not exists public.customer_leads (
  id bigint generated by default as identity primary key,
  name text,
  phone text,
  email text,
  interest text not null default 'الكل',
  marketing_consent boolean not null default false,
  source text not null default 'website_popup',
  created_at timestamptz not null default now(),
  constraint customer_leads_contact_required check (nullif(trim(coalesce(phone, '')), '') is not null or nullif(trim(coalesce(email, '')), '') is not null)
);

alter table public.customer_leads enable row level security;

-- Public visitors may only submit opted-in leads. They cannot read, edit, or delete leads.
drop policy if exists "Visitors can submit opted-in STEPUP leads" on public.customer_leads;
create policy "Visitors can submit opted-in STEPUP leads"
on public.customer_leads
for insert
to anon, authenticated
with check (marketing_consent = true);
